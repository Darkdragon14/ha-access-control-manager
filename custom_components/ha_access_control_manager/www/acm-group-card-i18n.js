export function normalizeLanguage(language) {
  if (typeof language !== "string") return "en";
  const base = language.trim().toLowerCase().split(/[-_]/)[0];
  return Object.hasOwn(translations, base) ? base : "en";
}

export function translate(language, key, values = {}) {
  const dictionary = translations[normalizeLanguage(language)];
  const localized = Object.hasOwn(dictionary, key) ? dictionary[key] : undefined;
  const english = Object.hasOwn(translations.en, key) ? translations.en[key] : undefined;
  const text = typeof localized === "string" ? localized : typeof english === "string" ? english : key;
  return text.replace(/\{(\w+)\}/g, (placeholder, name) =>
    values != null && Object.hasOwn(values, name) ? String(values[name]) : placeholder);
}
